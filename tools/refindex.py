#!/usr/bin/env python3
"""refs INDEX.md: which document decides what, from the key table.

    python3 METHOD/tools/refindex.py [--out FILE] [--check]

Reads method.toml [references.keys] and [references.decides], and writes
one table: key, what it decides (the subjects, in a few words), the file
and its size, whether it is present. The agent reads this before writing a
test case, a row or a fix, to pick the key that decides the expected
result; without it the library is 140 files and the one remembered gets
picked.

[references.decides] maps a key to its subjects. A key with no entry is
listed with "(subject not written)"; --check exits 1 while any hand-named
key (one not starting with DOC_) lacks one, or any key's file is missing.
Generated keys (DOC_...) are listed from their file names.

The default output is <reference worktree>/INDEX.md, which is not
committed on the reference-library branch (the file is regenerated); a
copy at context/REFS.md is what the session-recall hook prints the head of.

Order (r3.6): hand-named keys first, the most cited first, so the head the
recall hook prints shows SBG and MSCDEX rather than whichever chipset
number sorts first. A key's citations are counted over the matrix's
`decides` fields and the rows on [rows] refs (every `KEY:` or `KEY ` token);
ties and uncited keys fall back to the name. Generated keys follow, in the
same order among themselves.
"""

from pathlib import Path
import argparse
import re
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'lib'))
import methodlib  # noqa: E402
import refcheck  # noqa: E402

KEYS = refcheck.KEYS
DECIDES = {str(k): str(v) for k, v in methodlib.CONFIG.get('references', {}).get('decides', {}).items()}


def size_of(path):
    try:
        n = path.stat().st_size
    except OSError:
        return 'missing'
    return f'{n // 1024} KB' if n >= 1024 else f'{n} B'


ROW_REFS = list(methodlib.CONFIG.get('rows', {}).get('refs', []))
ROW_PATHS = list(methodlib.CONFIG.get('rows', {}).get('paths', []))


def cited_text():
    """Everything a key may be cited in: the matrix file and the rows on the row refs."""
    parts = []
    matrix = methodlib.PACKAGE / 'matrix' / 'matrix.toml'
    if matrix.exists():
        parts.append(matrix.read_text(errors='replace'))
    for ref in ROW_REFS:
        for pattern in ROW_PATHS:
            if '*' in pattern:
                listed = subprocess.run(['git', 'ls-tree', '--name-only', '-r', ref, '--', pattern.split('*')[0]],
                                        capture_output=True, text=True)
                names = [n for n in listed.stdout.split() if Path(n).match(pattern)]
            else:
                names = [pattern]
            for name in names:
                shown = subprocess.run(['git', 'show', f'{ref}:{name}'], capture_output=True, text=True,
                                       errors='replace')
                if shown.returncode == 0:
                    parts.append(shown.stdout)
    return '\n'.join(parts)


def citations(keys, text):
    """How often each key is cited: KEY followed by a colon or whitespace, as a whole token."""
    counts = {}
    for key in keys:
        counts[key] = len(re.findall(r'(?<![\w-])' + re.escape(key) + r'(?=[:\s,;)])', text))
    return counts


def ordered(keys, counts):
    """Hand-named keys by citations descending then name; DOC_ keys after, the same way."""
    return sorted(keys, key=lambda k: (k.startswith('DOC_'), -counts.get(k, 0), k))


def rows(tree):
    out, missing, unsubjected = [], [], []
    counts = citations(KEYS, cited_text())
    for key in ordered(KEYS, counts):
        name = KEYS[key]
        path = tree / name if tree else None
        present = refcheck.held(name, tree)
        if not present:
            missing.append(key)
        subject = DECIDES.get(key)
        if not subject:
            if key.startswith('DOC_'):
                subject = '(' + Path(name).stem.replace('_', ' ') + ')'
            else:
                subject = '(subject not written)'
                unsubjected.append(key)
        size = size_of(path) if path else 'in a worktree or on a row ref'
        out.append((key, subject, name, size, present, counts.get(key, 0)))
    return out, missing, unsubjected


def render(table, tree):
    lines = ['# Reference index: which document decides what', '',
             f'Generated by tools/refindex.py from method.toml [references]; worktree {tree}. Do not edit: regenerate.',
             'Before writing a test case, a row or a fix: find the subject below, open that key, and quote the line '
             'that decides the expected result. A subject no key covers is `silent`, and the row says what decides instead.',
             'Hand-named keys first, the most cited in rows and tests first; generated keys after.',
             '', '| Key | Decides | File | Size | Cited |', '|---|---|---|---|---|']
    for key, subject, name, size, present, cited in table:
        flag = '' if present else ' **MISSING**'
        lines.append(f'| `{key}` | {subject} | {name}{flag} | {size} | {cited} |')
    lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--out')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tree = refcheck.worktree()
    table, missing, unsubjected = rows(tree)
    text = render(table, tree)
    out = Path(args.out) if args.out else (tree / 'INDEX.md' if tree else Path('INDEX.md'))
    out.write_text(text)
    print(f'{out}: {len(table)} keys, {len(missing)} missing files, {len(unsubjected)} hand-named keys without a subject')
    if missing:
        print('missing: ' + ', '.join(missing))
    if unsubjected:
        print('no subject: ' + ', '.join(unsubjected))
    return 1 if args.check and (missing or unsubjected) else 0


if __name__ == '__main__':
    sys.exit(main())
